const MacroInstruction MacroInstruction::invalid = MacroInstruction(0x00, "INVALID", MacroOperand::None);

const MacroInstruction& MacroInstruction::get_instruction(MacroType type, uint8_t opcode) {
    switch (type) {
        case MacroType::Mesa:
            return mesa_instruction_table[opcode];
        case MacroType::Lisp:
            return lisp_instruction_table[opcode];
        default:
            return invalid;
    }
}

